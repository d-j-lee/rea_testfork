"""Regenerate eval scaffold scripts from their single sources.

Eval runs start in an empty workspace and cannot read the case directory, so a
scaffold must carry its fixtures inline. This script embeds the sandbox
incident generator and workspace config; tests/test_evals.py fails when the
committed scaffold is stale. Usage: python tools/build_eval_fixtures.py
"""

from __future__ import annotations

from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SANDBOX = ROOT / "examples" / "sandbox"
CASE = ROOT / "plugins" / "devloop" / "evals" / "investigate-dup-reward"

CONFIG = r"""display_tz = "UTC"

[env.incident]
tier = "live"
markers = ["incident.db"]

[env.incident.db]
driver = "sqlite"
dialect = "sqlite"
path = "run/incident/incident.db"
mask_columns = ["account"]

[log.profiles.sandbox]
pattern = '^(?P<ts>\d{4}-\d{2}-\d{2} \d{2}:\d{2}:\d{2}\.\d{3}) \[(?P<level>[A-Z]+)\] \[(?P<server>[\w-]+)\] \[(?P<thread>[\w-]+)\] (?P<msg>.*)$'
ts_format = "%Y-%m-%d %H:%M:%S.%f"
tz = "+09:00"
"""


def scaffold() -> str:
    gen = (SANDBOX / "incident" / "generate.py").read_text(encoding="utf-8")
    assert "DEVLOOP_EOF" not in gen
    return (
        "#!/usr/bin/env bash\n"
        "# GENERATED by tools/build_eval_fixtures.py from examples/sandbox/incident/generate.py. Do not edit.\n"
        "set -euo pipefail\n"
        "mkdir -p .devloop/cases run/incident\n"
        "cat > .devloop/config.toml <<'DEVLOOP_EOF'\n" + CONFIG + "DEVLOOP_EOF\n"
        "python3 - --out run/incident <<'DEVLOOP_EOF'\n" + gen + "DEVLOOP_EOF\n"
    )


def main() -> None:
    path = CASE / "scaffold.sh"
    path.write_text(scaffold(), encoding="utf-8", newline="\n")
    path.chmod(0o755)
    print(f"wrote {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
