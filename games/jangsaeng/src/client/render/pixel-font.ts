/**
 * Rows for a whole string (glyphs separated by one blank column), or null
 * when any character is missing from the font. Lower-case maps to upper.
 */
export function glyphRows(text: string): string[] | null {
  const rows: string[] = ["", "", "", "", ""];
  let first = true;
  for (const ch of text) {
    const g = GLYPHS[ch] ?? GLYPHS[ch.toUpperCase()];
    if (!g) return null;
    for (let r = 0; r < FONT_H; r++) rows[r] += (first ? "" : ".") + (g[r] as string);
    first = false;
  }
  return first ? null : rows;
}
